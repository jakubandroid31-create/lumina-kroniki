  if(it.heal){const amt=it.heal<=1?Math.ceil(st.hp*it.heal):it.heal;const d=Math.min(st.hp-mon.hp,amt);
    if(d>0){mon.hp+=d;msgs.push(t('p_heal',nm,d));}}
