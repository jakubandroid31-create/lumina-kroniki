  let _arena=false;
  if(B.kind==='boss'&&typeof drawBossArena==='function'&&typeof world!=='undefined'&&world){try{drawBossArena(ctx,world.li,tm,(B.final&&B.ei>0)?2:1);_arena=true;}catch(e){_arena=false;}}
