function _bRenderEvo(tm){
  const B=battle,ev=B.ev;
  const g=ctx.createLinearGradient?ctx.createLinearGradient(0,0,0,H):null;
  if(g&&g.addColorStop){g.addColorStop(0,'#101830');g.addColorStop(1,'#402850');ctx.fillStyle=g;}else ctx.fillStyle='#181830';
  ctx.fillRect(0,0,W,H);
  for(let i=0;i<24;i++){const a=i/24*Math.PI*2+tm*0.6;ctx.fillStyle=i%2?'#ffffff22':'#ffe08022';ctx.fillRect(W/2+Math.cos(a)*(80+Math.sin(tm*2+i)*20),110+Math.sin(a)*60,3,3);}
  const e=tm-ev.t0;
  let sp=ev.from,white=false;
  if(!ev.done){white=e>0.6;if(white){const f=Math.min(12,1+e*3);const ph=Math.sin(e*f*Math.PI);sp=ph>0?ev.from:ev.to;}}
  else{sp=ev.to;white=(tm-(ev.t1||tm))<0.3;}
  const spr=_bSprite(sp);
  if(spr){const sc=4,w=spr.width*sc,h=spr.height*sc;const k=white&&!ev.done?0.9+0.1*Math.abs(Math.sin(e*6)):1;
    ctx.save();ctx.translate(W/2,150);ctx.scale(k,k);ctx.drawImage(white?_bWhite(spr):spr,-w/2,-h,w,h);ctx.restore();}
  if(B.flash>0){ctx.save();ctx.globalAlpha=clamp(B.flash,0,1);ctx.fillStyle='#fff';ctx.fillRect(0,0,W,H);ctx.restore();}
}

