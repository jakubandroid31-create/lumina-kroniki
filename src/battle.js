async function runBattle(o){
  o=o||{};
  const team=(o.team||[]).filter(Boolean);
  if(o.final&&team.length<2&&typeof SPECIES!=='undefined'&&SPECIES.eclipsor2&&typeof createMon==='function'){
    const b=team[0];team.push(createMon('eclipsor2',(b?b.lv:50)+2,b&&b.mul?Object.assign({},b.mul):undefined));
  }
  let ai=game.party.findIndex(m=>m&&m.hp>0);
  if(!team.length)return 'win';
  if(ai<0)return 'lose';
  battle={kind:o.kind||'wild',o,final:!!o.final,tname:L2(o.tname)||'',team,ei:0,ai,
    stages:{a:{atk:0,def:0},e:{atk:0,def:0}},dA:game.party[ai].hp,dE:team[0].hp,
    an:{a:_bNewAn(),e:_bNewAn()},parts:[],evo:new Set(),runs:0,showA:false,showE:false,
    flash:0,particles:[],orb:null,mvInfo:null,ev:null,lastCmd:0,over:false};
  let res='run';
  try{res=await _bMain();}catch(e){console.error('battle error',e);res=_bE()&&_bE().hp<=0?'win':'run';}
  battle.over=true;battle.mvInfo=null;
  if(res==='lose')return 'lose';
  try{
    if(res==='win'||res==='caught'){
      for(const m of game.party.concat(game.box||[]))if(battle.evo.has(m)&&m.hp>0)await _bEvolve(m);
    }
    if(!game.party.some(m=>m.hp>0)&&game.party[0]){game.party[0].hp=1;await _bSay(t('b_revive',_bName(game.party[0])));}
  }catch(e){console.error(e);}
  battle.stages={a:{atk:0,def:0},e:{atk:0,def:0}};
  await _bTrans('in');
  scene='world';
  try{_bMusic(LEVELS[world.li].music);}catch(e){}
  battle=null;
  await _bTrans('out');
  return res;
}

async function _bMain(){
  const B=battle;
  _bSfx('enc');
  await _bTrans('in');
  scene='battle';
  _bMusic(B.final?'final':B.kind==='boss'?'boss':B.kind==='trainer'?'trainer':'battle');
  const E=_bE();
  _bSeen(E);
  B.an.e.vis=true;
  if(B.kind!=='wild'){B.an.e.app=0;B.an.e.appTo=0;}
  await _bTrans('out');
  if(B.kind==='wild'){B.showE=true;await _bSay(t('b_wild',_bName(E)));}
  else if(B.kind==='trainer'){
    await _bSay(t('b_trainer',B.tname||'?'));
    await _bSendEnemy(true);
  }else{
    await _bSendEnemy(false);
    await _bSay(t('b_boss',_bName(E)));
  }
  await _bSendAlly();
  // main loop
  for(let turn=0;turn<2000;turn++){
    const act=await _bCommand();
    const r=await _bTurn(act);
    if(r)return r;
  }
  return 'run';
}

