  B.dA=A.hp;B.stages.a={atk:0,def:0};
  if(!B.parts.includes(A))B.parts.push(A);
  B.an.a=_bNewAn();B.an.a.vis=true;B.an.a.app=0;B.an.a.appTo=1;B.an.a.flash=1;
  if(!SET.battleAnim)B.an.a.app=1;
